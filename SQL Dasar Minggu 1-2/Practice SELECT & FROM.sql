Soal 1
Manager ingin melihat semua data.
JAWABAN
SELECT * 
FROM sales;

Soal 2
Manager hanya ingin melihat product dan quantity
JAWABAN
SELECT product, quantity
FROM sales;

Soal 3
Manager ingin melihat product category price
JAWABAN
SELECT product, category, price
FROM sales;

Soal 4
Manager berkata "Saya ingin melihat ID transaksi, produk, dan harga."
Kolom apa saja yang harus kamu ambil?
JAWABAN
SELECT transaction_id, product, price
FROM sales;
