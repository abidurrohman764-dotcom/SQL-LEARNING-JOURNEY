Operator	Arti
=	sama dengan
>	lebih besar
<	lebih kecil
>=	lebih besar atau sama dengan
<=	lebih kecil atau sama dengan
<>	tidak sama dengan

Contoh:
Lebih besar dari
WHERE quantity > 10
  
Lebih kecil dari
WHERE quantity < 10
  
Lebih besar atau sama dengan
WHERE quantity >= 10
Artinya:
quantity 10 ikut masuk.

Lebih kecil atau sama dengan
WHERE quantity <= 10
  
Tidak sama dengan
WHERE category <> 'Sembako'

Artinya:
Ambil data yang kategorinya bukan Sembako.
